/** Minimal RFC 4180-style parser: quoted fields, doubled quotes, configurable delimiter. Returns one array per line. */
export function parseCsv(text: string, delimiter: string): string[][] {
  const rows: string[][] = []
  let row: string[] = []
  let field = ''
  let quoted = false
  const src = text.replace(/^﻿/, '')
  for (let i = 0; i < src.length; i++) {
    const c = src[i]
    if (quoted) {
      if (c === '"' && src[i + 1] === '"') { field += '"'; i++ }
      else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === delimiter) { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && src[i + 1] === '\n') i++
      row.push(field); rows.push(row); row = []; field = ''
    } else field += c
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row) }
  return rows.filter((r) => r.some((f) => f.trim() !== ''))
}

export function toCsv(rows: string[][], delimiter = ';'): string {
  const escape = (f: string) => (/[";\n\r,]/.test(f) ? `"${f.replace(/"/g, '""')}"` : f)
  return rows.map((r) => r.map(escape).join(delimiter)).join('\r\n') + '\r\n'
}
